namespace Stateforge\Scenario\SymfonyAi\Console\Command;

use Stateforge\Scenario\Ai\Runtime\Ai;
use Stateforge\Scenario\Ai\Runtime\Maker\CodeMaker;
use Stateforge\Scenario\Ai\Runtime\Prompt\ClassNameParser;
use Stateforge\Scenario\Ai\Runtime\SourceCodeReader;
use Stateforge\Scenario\Core\Contract\CliOutput;
use Stateforge\Scenario\Core\Runtime\Application;
use Stateforge\Scenario\Symfony\Console\Command\ScenarioCommand;
use Stateforge\Scenario\Symfony\Console\Output;
use Stateforge\Scenario\SymfonyAi\Runtime\Context;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Output\OutputInterface;
use Symfony\Component\Console\Style\SymfonyStyle;
use function class_exists;
use function count;
use function preg_replace;
use function sprintf;
use const PHP_EOL;

final class ScenarioAiMakeCommand extends ScenarioCommand
{
    protected function configure(): void
    {
        $this
            ->setName('scenario:ai:make')
            ->setDescription('Make a scenario or parameter type with AI - should only be used for dev/test')
        ;
    }

    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        (new Application())->prepare();

        $style = new Output(new SymfonyStyle($input, $output));

        $style->note(
            'Welcome to Scenario Symfony AI!' . PHP_EOL .
            'Scenario Symfony AI helps you create Scenarios and Parameter Types for a Symfony application using artificial intelligence.' . PHP_EOL .
            'Simply describe what you want to achieve, and the AI will generate the corresponding PHP code based on the Scenario Symfony framework.' . PHP_EOL .
            'If additional information is required, the AI may ask follow-up questions or request access to specific project classes.' . PHP_EOL .
            'Your project stays under your control: No project-specific documentation or source code will be shared with the AI without your explicit consent.',
        );

        if (Ai::config()->projectDoc === null) {
            $style->warn('To get better results, configure your project doc, that the AI knows better what to do.');
        }

        $ai = Ai::start(new Context());

        $prompt = $style->ask(
            'Please describe the scenario or parameter type.',
        ) ?? '';
        $ai->talk($this->prompt($style, $prompt));
        while ($ai->completed() === false) {
            $prompt = '';
            if ($ai->question() !== null) {
                $prompt .= $this->prompt(
                    $style,
                    $style->ask('AI: ' . $ai->question()) ?? '',
                );
            }
            if (count($ai->classes()) > 0) {
                $prompt .= $this->sources($style, $ai->classes());
            }

            $ai->talk($this->prompt($style, $prompt));
        }

        $response = $ai->response();
        if ($response->type === null
            || $response->php === null) {
            $style->error('No code was generated by AI, please try again.');
            return Command::FAILURE;
        }

        $file = (new CodeMaker())->make($response->type, $response->php);
        $style->success(
            'Code "' . $file . '" generated successfully.' . PHP_EOL .
            'The generated code has been validated and saved.' . PHP_EOL .
            'Review the implementation and rename the file to "' . preg_replace('/(?:\.\d+)?\.ai$/', '', $file) . '" to activate it.',
        );
        return Command::SUCCESS;
    }

    private function prompt(CliOutput $output, string $prompt): string
    {
        return $prompt . $this->sources($output, (new ClassNameParser())->parse($prompt));
    }

    /**
     * @param list<string> $classes
     */
    private function sources(CliOutput $output, array $classes): string
    {
        /** @var list<class-string> $sources */
        $sources = [];
        foreach ($classes as $class) {
            if (class_exists($class) === false) {
                continue;
            }

            if ($output->confirm(sprintf('Can the source code for class "%s" be sent to AI?', $class), false) === true) {
                $sources[] = $class;
            }
        }

        return (new SourceCodeReader())->read($sources);
    }
}
